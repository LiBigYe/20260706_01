/* ========================================================================== */
/*  运行时状态                                                                 */
/* ========================================================================== */

static TIM_HandleTypeDef *pwm_htim;
static uint32_t pwm_phase_acc;
static uint32_t pwm_phase_inc;
static uint8_t  pwm_output_on;

/* ========================================================================== */
/*  公开 API                                                                   */
/* ========================================================================== */

void PWM_DDS_Init(TIM_HandleTypeDef *htim_pwm)
{
    pwm_htim = htim_pwm;

    HAL_TIM_PWM_Start(htim_pwm, TIM_CHANNEL_1);
    __HAL_TIM_MOE_ENABLE(htim_pwm);

    pwm_phase_acc  = 0;
    pwm_phase_inc  = FSK4_GetPhaseInc(0);  /* 默认 1500 Hz */
    pwm_output_on  = 1;
}

void PWM_DDS_SetFreq(uint8_t digit)
{
    if (digit < 4) {
        pwm_phase_inc = FSK4_GetPhaseInc(digit);
    }
}

/**
  * @brief  输出 DC 中值 (保护间隔 / 静态待机)
  *
  *   重置相位状态, 立即写 CCR1 = 512 (50% 占空比 = 1.65V DC).
  *   直接写硬件寄存器, 不依赖 PWM_DDS_Tick()。
  */
void PWM_DDS_OutputMidscale(void)
{
    pwm_phase_inc  = 0;
    pwm_phase_acc  = 0;
    if (pwm_htim != NULL) {
        __HAL_TIM_SET_COMPARE(pwm_htim, TIM_CHANNEL_1, PWM_DDS_MIDSCALE);
    }
}

void PWM_DDS_Shutdown(void)
{
    if (pwm_output_on && pwm_htim != NULL) {
        HAL_TIM_PWM_Stop(pwm_htim, TIM_CHANNEL_1);
        pwm_output_on = 0;
    }
}

void PWM_DDS_Start(void)
{
    if (!pwm_output_on && pwm_htim != NULL) {
        HAL_TIM_PWM_Start(pwm_htim, TIM_CHANNEL_1);
        __HAL_TIM_MOE_ENABLE(pwm_htim);
        pwm_output_on = 1;
    }
}

/**
  * @brief  DDS 单步 — 由 TIM3 ISR (16kHz) 调用
  *
  *   1024-point LUT: 取 phase_acc[31:22] = 10-bit index (0~1023).
  *   LUT 为 10-bit 原生值, 直接写入 CCR1 无需缩放。
  */
void PWM_DDS_Tick(void)
{
    pwm_phase_acc += pwm_phase_inc;

    uint16_t idx = (uint16_t)(pwm_phase_acc >> 22);

    __HAL_TIM_SET_COMPARE(pwm_htim, TIM_CHANNEL_1, sine_lut[idx]);
}
