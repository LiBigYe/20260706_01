/**
  ******************************************************************************
  * @file           : pwm_dds.c
  * @brief          : PWM-based DDS Sine Generator Implementation (v4)
  *
  *   DDS 公式:  phase_inc = (f_out / f_sample) × 2^32
  *              idx = (phase_acc >> 22) & 0x3FF  (10-bit index → 0~1023)
  *              ccr = sine_lut[idx]              (10-bit 原生值)
  *
  *   TIM1 PWM 时序:
  *     ARR=1023, PSC=0, 50MHz → 48.83kHz PWM carrier
  *     CCR1 更新间隔: 16kHz (约每 3 个 PWM 周期更新一次)
  *
  *   10-bit LUT:
  *     center=512, amp=510, 范围[2, 1022]
  *     正半周: +510 阶 (CCR1: 512→1022), 负半周: -510 阶 (CCR1: 512→2)
  *     Vpp = 3.3V × 1020/1024 ≈ 3.287V
  *
  *   RC 滤波器:
  *     1kΩ + 47nF: fc≈3.4kHz, 48.8kHz衰减≈-23dB (载波残留≈230mVpp→改善到~70mVpp)
  *     1kΩ + 100nF: fc≈1.6kHz, 48.8kHz衰减≈-30dB (更干净)
  ******************************************************************************
  */

